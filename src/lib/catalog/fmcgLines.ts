import type { CatalogPackSpec, MasterCategory, ProductFamilySpec, SupplierTierLabel } from './types';

function fmcgFam(
  prefix: string,
  category: MasterCategory,
  brand: string,
  supplierTier: SupplierTierLabel,
  packs: CatalogPackSpec[],
  entries: Array<[string, number, number]>
): ProductFamilySpec {
  return {
    prefix,
    category,
    brand,
    supplierTier,
    pricingMode: 'packet_mrp',
    packs,
    items: entries.map(([title, refValue, targetMarginPct]) => ({
      title,
      refValue,
      targetMarginPct,
    })),
  };
}

