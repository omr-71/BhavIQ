import type { CatalogPackSpec, MasterCategory, ProductFamilySpec, SupplierTierLabel } from './types';

function packFam(
  prefix: string,
  category: MasterCategory,
  brand: string,
  supplierTier: SupplierTierLabel,
  packs: CatalogPackSpec[],
  entries: Array<[string, number, number, string?]>
): ProductFamilySpec {
  return {
    prefix,
    category,
    brand,
    supplierTier,
    pricingMode: 'packet_mrp',
    packs,
    items: entries.map(([title, refValue, targetMarginPct, agriCommodityKey]) => ({
      title,
      refValue,
      targetMarginPct,
      agriCommodityKey,
    })),
  };
}

function looseFam(
  prefix: string,
  brand: string,
  packs: CatalogPackSpec[],
  entries: Array<[string, number, number, string?]>
): ProductFamilySpec {
  return {
    prefix,
    category: 'Loose Items',
    brand,
    supplierTier: 'Agri-Commodity Bulk Index',
    pricingMode: 'loose_kg',
    packs,
    items: entries.map(([title, refValue, targetMarginPct, agriCommodityKey]) => ({
      title,
      refValue,
      targetMarginPct,
      agriCommodityKey,
    })),
  };
}

